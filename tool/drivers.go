package main

import (
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func drivers(args []string) error {
	flags := flag.NewFlagSet("drivers", flag.ExitOnError)
	config := flags.String("config", "config", "directory holding the driver lists")
	target := flags.String("target", "", "the target whose lists to read beside common's")
	source := flags.String("source", ".", "kernel source")
	dotconfig := flags.String(
		"dotconfig",
		".config",
		"the config resolved without the driver lists",
	)
	parse(flags, args)
	return writeDrivers(*config, *target, *source, *dotconfig, os.Stdout)
}

// A line in a driver list is a kernel source directory. Every tristate option
// defined under one is asked for as a module, unless the resolved config already sets
// it or a -REGEX line matches it. A bool option is turned on only where a
// +REGEX line matches it, which is how the menus drivers sit behind open.
func writeDrivers(config, target, source, dotconfig string, w io.Writer) error {
	paths, err := lists(config, target, "drivers")
	if err != nil {
		return err
	}
	lines, err := entries(paths)
	if err != nil {
		return err
	}

	var dirs []string
	var gates, skips []*regexp.Regexp
	seen := map[string]bool{}
	for _, line := range lines {
		switch line[0] {
		case '+', '-':
			re, err := regexp.Compile(line[1:])
			if err != nil {
				return fmt.Errorf("%q is not a regular expression: %v", line, err)
			}
			if line[0] == '+' {
				gates = append(gates, re)
			} else {
				skips = append(skips, re)
			}
		default:
			if !seen[line] {
				seen[line] = true
				dirs = append(dirs, line)
			}
		}
	}
	sort.Strings(dirs)

	set, err := setSymbols(dotconfig)
	if err != nil {
		return err
	}

	tristates, bools := map[string]bool{}, map[string]bool{}
	for _, dir := range dirs {
		files, err := kconfigs(filepath.Join(source, dir))
		if err != nil {
			return err
		}
		for _, file := range files {
			symbols, err := parseKconfig(file)
			if err != nil {
				return err
			}
			for name, kind := range symbols {
				if kind == "tristate" {
					tristates[name] = true
				} else {
					bools[name] = true
				}
			}
		}
	}

	wanted := func(name string) bool { return !set[name] && !matchesAny(skips, name) }
	var modules, opened []string
	for _, name := range sorted(tristates) {
		if wanted(name) {
			modules = append(modules, name)
		}
	}
	for _, name := range sorted(bools) {
		if !tristates[name] && matchesAny(gates, name) && wanted(name) {
			opened = append(opened, name)
		}
	}

	names := make([]string, len(paths))
	for i, p := range paths {
		names[i] = filepath.Base(p)
	}
	fmt.Fprintf(w, "# Generated by kernel-tool drivers from %s.\n", strings.Join(names, ", "))
	fmt.Fprintf(
		w,
		"# %d directories, %d tristate symbols, %d not already set.\n",
		len(dirs),
		len(tristates),
		len(modules),
	)
	for _, name := range opened {
		fmt.Fprintf(w, "CONFIG_%s=y\n", name)
	}
	for _, name := range modules {
		fmt.Fprintf(w, "CONFIG_%s=m\n", name)
	}
	fmt.Fprintf(
		os.Stderr,
		"drivers: %d directories, %d modules and %d menus asked for, %d already set or left alone\n",
		len(dirs),
		len(modules),
		len(opened),
		len(tristates)-len(modules),
	)
	return nil
}

func matchesAny(res []*regexp.Regexp, name string) bool {
	for _, re := range res {
		if re.MatchString(name) {
			return true
		}
	}
	return false
}

var setLine = regexp.MustCompile(`^CONFIG_([A-Za-z0-9_]+)=`)

func setSymbols(dotconfig string) (map[string]bool, error) {
	lines, err := readLines(dotconfig)
	if err != nil {
		return nil, err
	}
	set := map[string]bool{}
	for _, line := range lines {
		if m := setLine.FindStringSubmatch(line); m != nil {
			set[m[1]] = true
		}
	}
	return set, nil
}

// kconfigs finds every Kconfig file under a directory. A directory the kernel
// does not have is an error: a line that silently matches nothing is a
// driver family quietly gone.
func kconfigs(dir string) ([]string, error) {
	info, err := os.Stat(dir)
	if err != nil || !info.IsDir() {
		return nil, fmt.Errorf("%s is not in this kernel", dir)
	}
	var files []string
	err = filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if strings.HasPrefix(d.Name(), ".") && path != dir {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Type().IsRegular() && strings.HasPrefix(d.Name(), "Kconfig") {
			files = append(files, path)
		}
		return nil
	})
	sort.Strings(files)
	return files, err
}

var (
	configLine   = regexp.MustCompile(`^\s*(?:menu)?config\s+([A-Za-z0-9_]+)\s*$`)
	helpLine     = regexp.MustCompile(`^\s+(?:---)?help(?:---)?\s*$`)
	tristateLine = regexp.MustCompile(`^\s+(?:def_)?tristate\b`)
	boolLine     = regexp.MustCompile(`^\s+(?:def_)?bool\b`)
)

// parseKconfig reads each symbol's type from the first type line after its
// config line, and stops looking at its help text.
func parseKconfig(file string) (map[string]string, error) {
	lines, err := readLines(file)
	if err != nil {
		return nil, err
	}
	symbols := map[string]string{}
	current := ""
	for _, line := range lines {
		switch {
		case configLine.MatchString(line):
			current = configLine.FindStringSubmatch(line)[1]
		case current != "" && helpLine.MatchString(line):
			current = ""
		case current != "" && tristateLine.MatchString(line):
			symbols[current] = "tristate"
			current = ""
		case current != "" && boolLine.MatchString(line):
			if symbols[current] != "tristate" {
				symbols[current] = "bool"
			}
			current = ""
		}
	}
	return symbols, nil
}
